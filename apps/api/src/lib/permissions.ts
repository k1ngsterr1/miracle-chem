export function hasPermission(role: UserRole, permission: Permission): boolean {
  return access[permission].includes(role);
}

export function requirePermission(role: UserRole, permission: Permission): void {
  if (hasPermission(role, permission)) return;
  throw new ApiError(403, "ACCESS_FORBIDDEN", "Недостаточно прав для этого действия");
}

export function canAccessOwnDocumentsOnly(role: UserRole): boolean {
  return role === UserRole.MANAGER;
}
